/* ===========================================================================
 * 帧率下限与实测基线。单独成文件，因为它有两条判词相反的断言在守，
 * 而那两条需要能在快闸门里零依赖地跑。
 * ===========================================================================
 *
 * 这个下限的职责**只有一个**：抓彻底卡死 / 白屏 / 死循环。它不是性能基准。
 * CI 上是共享 CPU，紧到正常波动就会撞的下限是一台假红工厂，而假红会逗人
 * 去改产品迁就尺子。
 *
 * 两条断言守它，判词不同，两侧都会红：
 *   - 太松：下限 <= 0 就是空断言。
 *   - 太紧：三倍下限超过实测基线就红。
 *
 * **而第一个违反“太紧”那条的人是我自己：** 上一轮写了下限 13 配基线 38，
 * 而 13*3 = 39 > 38，当场红。正确动作是改下限（改成 12，36 <= 38），
 * **不是把守卫从三倍放宽到两倍**,那等于把断言改成装饰，而且是我亲手改的。
 *
 * BASELINE 只许从真实的 CI 指标更新，不许拍。两轮实测到过 38 和 39，
 * 这里留保守的那个。
 * ======================================================================== */

export const FPS_FLOOR = 12;
export const FPS_MEASURED_BASELINE = 38;
export const FPS_MARGIN_MULTIPLE = 3;

export function floorIsNotEmpty(floor = FPS_FLOOR){
  return floor > 0;
}

export function floorKeepsMargin(floor = FPS_FLOOR, baseline = FPS_MEASURED_BASELINE){
  return floor * FPS_MARGIN_MULTIPLE <= baseline;
}
